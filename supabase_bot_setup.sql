-- ============================================================================
-- Supabase database setup for the Khmer Telegram AI/TTS bot
-- Generated from the tables and columns used by:
--   updated_bot_khmer_progress_single_message.py
--
-- Run this entire file once in:
--   Supabase Dashboard -> SQL Editor -> New query -> Run
--
-- SECURITY:
--   The bot server must use SUPABASE_SERVICE_ROLE_KEY.
--   Never expose the service-role/secret key in a browser or Telegram message.
-- ============================================================================

begin;

-- UUID generation used by feature_requests.
create extension if not exists pgcrypto with schema extensions;

-- --------------------------------------------------------------------------
-- Shared updated_at trigger
-- --------------------------------------------------------------------------
create or replace function public.bot_set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- --------------------------------------------------------------------------
-- 1. User preferences and Telegram profile cache
-- --------------------------------------------------------------------------
create table if not exists public.user_prefs (
  user_id bigint primary key,
  username text,
  first_name text,
  gender text not null default 'female',
  speed double precision not null default 1.0,
  tts_model text not null default 'auto',
  last_active timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_prefs_gender_check
    check (gender in ('female', 'male')),
  constraint user_prefs_speed_check
    check (speed >= 0.25 and speed <= 4.0)
);

-- Safe migration support for older deployments.
alter table public.user_prefs add column if not exists username text;
alter table public.user_prefs add column if not exists first_name text;
alter table public.user_prefs add column if not exists gender text default 'female';
alter table public.user_prefs add column if not exists speed double precision default 1.0;
alter table public.user_prefs add column if not exists tts_model text default 'auto';
alter table public.user_prefs add column if not exists last_active timestamptz;
alter table public.user_prefs add column if not exists created_at timestamptz default now();
alter table public.user_prefs add column if not exists updated_at timestamptz default now();

update public.user_prefs set gender = 'female' where gender is null;
update public.user_prefs set speed = 1.0 where speed is null;
update public.user_prefs set tts_model = 'auto' where tts_model is null;
update public.user_prefs set created_at = now() where created_at is null;
update public.user_prefs set updated_at = now() where updated_at is null;

create index if not exists user_prefs_username_lower_idx
  on public.user_prefs (lower(username));
create index if not exists user_prefs_last_active_idx
  on public.user_prefs (last_active desc);


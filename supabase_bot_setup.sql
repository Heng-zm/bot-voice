grant usage, select on all sequences in schema public to service_role;

-- Policies are explicit for clarity. A correctly configured service-role key
-- also bypasses RLS, but the bot must still remain server-side.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'user_prefs',
    'text_cache',
    'conversation_history',
    'scheduled_broadcasts',
    'blocked_users',
    'bot_settings',
    'bot_locks',
    'ai_api_keys',
    'feature_requests'
  ]
  loop
    execute format('drop policy if exists %I on public.%I', 'service_role_' || table_name || '_all', table_name);
    execute format(
      'create policy %I on public.%I for all to service_role using (true) with check (true)',
      'service_role_' || table_name || '_all',
      table_name
    );
  end loop;
end
$$;

